"""Builds the organised zip for the two-half flower hoop (run make_hoops_split.py first)."""
import zipfile, os, glob
SIZES = (60, 80, 100)
README = """\ufeffطارة تطريز وردة — مزخرفة من الناحيتين — جزء فوق + جزء تحت
=====================================================
الإطار جزئين: جزء فوق (فيه الحافة الدايرية البارزة والزخرفة) + جزء تحت (وردة مستوية، من غير حافة طالعة من ورا)
+ حلقة + مسامير منفصلة بتتحط بين الجزئين. كل حاجة بتتطبع نايمة على البليتة **من غير أي دعامات**.

جوه كل فولدر مقاس:
  1_الجزء_اللي_فوق_XXمم.stl   ← مرة واحدة. الناحية المستوية على البليتة والحافة والزخرفة لفوق.
  2_الجزء_اللي_تحت_XXمم.stl   ← مرة واحدة. زي ما هو في الملف (الزخرفة لفوق)، وبعدين بتقلبه وتركّبه.
  3_الحلقة_XXمم.stl           ← مرة واحدة، واقفة زي ما هي في الملف.
  4_المسامير_4_قطع.stl         ← 4 مسامير (3 + واحد احتياطي)، نايمين على البليتة.
  بليتة_جاهزة_XXمم.3mf        ← كل القطع مترتبة على بليتة A1 (مقاس 100 على بليتتين).

الأوزان (تقريبية — الحقيقي يظهر في Bambu Studio بعد الـ Slice):
  60 مم : الإطار ~16.5 جم (فوق 9.2 + تحت 7.3) + الحلقة ~4.4 جم   — الوردة 105 مم
  80 مم : الإطار ~22.5 جم (فوق 12.4 + تحت 10.1) + الحلقة ~5.8 جم — الوردة 130 مم
  100 مم: الإطار ~29.5 جم (فوق 16.0 + تحت 13.5) + الحلقة ~7.2 جم — الوردة 154 مم

إعدادات Bambu Studio (Bambu Lab A1):
  - PLA أو PLA Matte — فوهة 0.4 — 0.20mm Standard @BBL A1
  - Wall loops = 3 — Sparse infill = 15% Grid
  - Support = مقفول — البليتة Textured PEI
  - Top surface pattern = Monotonic line — Ironing = مقفول
  - المسامير صغيرة: لو اتحركت، شغّل Brim ليها بس (كليك يمين على المسامير ← Brim).
  - ماتعملش Scale لأي قطعة.

المسامير والتركيب (المسمار 2.5 مم والخرم 2.6 مم — مزنوق، مش سايب):
  1. دخّل المسامير التلاتة في الخروم اللي في الناحية المستوية للجزء اللي فوق (في الحافة). لو دخلت بصعوبة اضغطها بصباعك،
     ولو حسيت إنها سايبة حط نقطة سوبر جلو.
  2. اقلب الجزء اللي تحت (الزخرفة لبرا) وحطه عليه — المسامير بتدخل في خروم الجزء اللي تحت، وخرم التعليق بيقابل بعضه.
  3. اضغطهم على بعض (ونقطة غرا على الحرف لو عايز تثبيت دايم).
  4. افرد القماش على الحلقة واضغط الإطار عليها لحد ما تسمع تكة.

لو المسامير مش راضية تدخل خالص → اطلب نسخة بخرم 2.7 مم. لو سايبة أوي → خرم 2.55 مم.
"""
out = "طارة_الوردة_نصين_STL.zip"
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
    z.writestr("اقرأني_طريقة_الطباعة_والتركيب.txt", README)
    z.write("split_hoop_80mm.png", "صورة_الطارة_مقاس_80.png")
    for D in SIZES:
        sub = f"مقاس_{D}_مم"
        z.write(f"stl/split_{D}mm_top.stl", f"{sub}/1_الجزء_اللي_فوق_{D}مم.stl")
        z.write(f"stl/split_{D}mm_bottom.stl", f"{sub}/2_الجزء_اللي_تحت_{D}مم.stl")
        z.write(f"stl/split_{D}mm_ring.stl", f"{sub}/3_الحلقة_{D}مم.stl")
        z.write("stl/split_pins.stl", f"{sub}/4_المسامير_4_قطع.stl")
        plates = sorted(glob.glob(f"stl/split_{D}mm_plate*.3mf"))
        for p in plates:
            tag = "" if len(plates) == 1 else ("_1_فوق_وحلقة_ومسامير" if "1of2" in p else "_2_الجزء_اللي_تحت")
            z.write(p, f"{sub}/بليتة_جاهزة_{D}مم{tag}.3mf")
zz = zipfile.ZipFile(out)
print(out, len(zz.namelist()), "files", round(os.path.getsize(out) / 1e6, 1), "MB", "ok" if zz.testzip() is None else "BAD")
for n in zz.namelist(): print("  ", n)
